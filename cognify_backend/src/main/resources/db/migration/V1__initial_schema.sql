-- IF NOT EXISTS supports an explicitly baselined legacy Hibernate database.
CREATE TABLE IF NOT EXISTS accounts (
 id UUID PRIMARY KEY, email VARCHAR(255) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, name VARCHAR(255) NOT NULL, role VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS wallet (
 id UUID PRIMARY KEY, owner_id UUID NOT NULL UNIQUE, balance BIGINT NOT NULL, version BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS documents (
 id UUID PRIMARY KEY, owner_id UUID NOT NULL, title VARCHAR(255) NOT NULL, kind VARCHAR(255),
 content TEXT, updated_at TIMESTAMP WITH TIME ZONE, version BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS refreshsession (
 id UUID PRIMARY KEY, owner_id UUID NOT NULL, token_hash VARCHAR(255) NOT NULL UNIQUE,
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL, revoked BOOLEAN NOT NULL
);
CREATE TABLE IF NOT EXISTS cmscontent (
 id UUID PRIMARY KEY, content_key VARCHAR(255) NOT NULL UNIQUE, content_value TEXT NOT NULL
);
